const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const compiler=require('vue-template-compiler')
test('general order report shows currency next to each amount',()=>{
    const component=compiler.parseComponent(fs.readFileSync('modules/Report/Resources/assets/js/views/order_notes_general/index.vue','utf8'))
    assert.deepEqual(compiler.compile(component.template.content).errors,[])
    assert.match(component.template.content,/row\.currency_type_id/)
    assert.match(component.template.content,/row\.total/)
})
